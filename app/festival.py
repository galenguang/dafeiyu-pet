def today() -> datetime.date:
    return datetime.date.today()


def current(day: datetime.date | None = None) -> str | None:
    """返回今天的节日名，没有则 None。"""
    day = day or today()
    key = day.strftime("%m-%d")
    if key in SOLAR:
        return SOLAR[key]
    table = LUNAR.get(day.year)
    if table:
        for name, md in table.items():
            if md == key:
                return name
    return None


def upcoming(days: int = 30, day: datetime.date | None = None) -> list[tuple[int, str]]:
    """未来 N 天内的节日：[(剩余天数, 节日名)]。"""
    day = day or today()
    found: list[tuple[int, str]] = []
    for i in range(days + 1):
        d = day + datetime.timedelta(days=i)
        name = current(d)
        if name:
            found.append((i, name))
    return found


def festival_pool(name: str | None) -> list[str]:
    """节日对应的动作 id 列表；没有节日就返回全部节日动作。"""
    if name and name in FESTIVAL_ACTIONS:
        return FESTIVAL_ACTIONS[name]
    return []
